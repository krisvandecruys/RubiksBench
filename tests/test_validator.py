import random

import kociemba
import magiccube
import pytest

from rubiksbench.cube.color_scheme import STANDARD_ORIENTATIONS, STANDARD_SCHEME, ColorScheme
from rubiksbench.cube.facelets import CORNER_FACELETS, EDGE_FACELETS, FACES, facelet_index
from rubiksbench.cube.observation import Observation
from rubiksbench.cube.witness import SOLVED, apply_moves
from rubiksbench.evaluation.evaluator import validate
from rubiksbench.evaluation.taxonomy import Flag, Verdict

# Hand-transcribed from the sample images (top = U, front-left = F, front-right = R).
AI_IMAGE = {"U": "GRG WRO RRW", "F": "WYG GGB YYB", "R": "RWO YYR ROB"}  # an AI-generated cube
REAL_CUBE = {"U": "RWR BGB RYY", "F": "GOG ROR OYG", "R": "ORG WYG OYB"}  # a photo of a real cube


def scrambled(seed: int) -> str:
    """A reachable state in standard colors, Kociemba order, generated by magiccube."""
    random.seed(seed)
    cube = magiccube.Cube(3)
    cube.scramble(30)
    return cube.get_kociemba_facelet_colors()


def full(facelets: str) -> Observation:
    return Observation.from_facelet_string(facelets)


def corner_view(facelets: str) -> Observation:
    return full(facelets).restricted_to("UFR")


def relabel(facelets: str, mapping: dict[str, str]) -> str:
    return "".join(mapping.get(c, c) for c in facelets)


def swap(facelets: str, *pairs: tuple[int, ...]) -> str:
    s = list(facelets)
    for a, b in pairs:
        s[a], s[b] = s[b], s[a]
    return "".join(s)


def twist_corner(facelets: str, slot: int) -> str:
    a, b, c = CORNER_FACELETS[slot]
    s = list(facelets)
    s[a], s[b], s[c] = s[c], s[a], s[b]
    return "".join(s)


def assert_witness_agrees(observation: Observation, report) -> None:
    for check in (report.abstract, report.standard):
        if check.valid:
            assert check.witness.scramble_verified
            for observed, completed in zip(observation.stickers, check.witness.colors):
                assert observed in (None, completed)


def test_facelet_tables_partition_the_cube():
    centers = [9 * f + 4 for f in range(6)]
    indices = [i for group in CORNER_FACELETS + EDGE_FACELETS for i in group] + centers
    assert sorted(indices) == list(range(54))


def test_standard_scheme_has_24_orientations_and_excludes_its_mirror():
    assert len(STANDARD_ORIENTATIONS) == 24
    mirror = ColorScheme.from_mapping(STANDARD_SCHEME.as_dict() | {"R": "O", "L": "R"})
    assert mirror not in STANDARD_ORIENTATIONS


def test_real_cube_photo_is_valid_standard():
    observation = Observation.from_faces(REAL_CUBE)
    report = validate(observation)
    assert report.verdict == Verdict.VALID_STANDARD
    assert_witness_agrees(observation, report)


def test_ai_image_is_invalid():
    report = validate(Observation.from_faces(AI_IMAGE))
    assert report.verdict == Verdict.INVALID
    assert report.standard.flags == [Flag.DUPLICATE_PIECE, Flag.NO_LEGAL_COMPLETION]


@pytest.mark.parametrize("seed", range(10))
def test_scrambled_corner_views_are_valid_standard(seed):
    observation = corner_view(scrambled(seed))
    report = validate(observation)
    assert report.verdict == Verdict.VALID_STANDARD
    assert_witness_agrees(observation, report)


@pytest.mark.parametrize("seed", range(5))
def test_full_scrambled_cube_witness_is_the_cube_itself(seed):
    facelets = scrambled(seed)
    report = validate(full(facelets))
    assert report.verdict == Verdict.VALID_STANDARD
    assert "".join(report.standard.witness.colors) == facelets


def test_partial_observation_with_many_completions():
    # Only one face is seen: lots of completions exist and the witness is just one of them.
    observation = Observation.from_faces({"F": "RGB WGY OOW"})
    report = validate(observation)
    assert report.verdict == Verdict.VALID_STANDARD
    assert_witness_agrees(observation, report)


def test_duplicated_centers():
    observation = corner_view(scrambled(1)).with_stickers({facelet_index("R5"): "W"})
    report = validate(observation)
    assert report.verdict == Verdict.INVALID
    assert Flag.DUPLICATE_CENTERS in report.flags


def test_adjacent_opposite_standard_centers():
    # Swapping yellow and green puts yellow on F, next to white on U.
    observation = corner_view(relabel(scrambled(2), {"Y": "G", "G": "Y"}))
    report = validate(observation)
    assert report.verdict == Verdict.VALID_NONSTANDARD
    assert Flag.STANDARD_OPPOSITE_CENTERS_ADJACENT in report.flags
    assert_witness_agrees(observation, report)


def test_mirrored_scheme_keeps_opposites_but_fails_chirality():
    # Swapping red and orange mirrors the scheme; opposite pairs are unchanged.
    observation = corner_view(relabel(scrambled(3), {"R": "O", "O": "R"}))
    report = validate(observation)
    assert report.verdict == Verdict.VALID_NONSTANDARD
    assert report.flags == [Flag.STANDARD_CHIRALITY_INVALID]


def test_mirrored_scheme_with_all_six_centers():
    report = validate(full(relabel(scrambled(4), {"G": "B", "B": "G"})))
    assert report.verdict == Verdict.VALID_NONSTANDARD
    assert report.flags == [Flag.STANDARD_CHIRALITY_INVALID]


def test_edge_with_one_color_twice():
    facelets = scrambled(5)
    u8, f2 = EDGE_FACELETS[1]
    observation = corner_view(facelets).with_stickers({f2: facelets[u8]})
    report = validate(observation)
    assert report.verdict == Verdict.INVALID
    assert Flag.IMPOSSIBLE_EDGE in report.flags


def test_edge_with_standard_opposite_colors():
    # A white-yellow edge between the U and F faces cannot exist on a standard cube.
    observation = Observation.from_faces({"U": "....W..W.", "F": ".Y..G...."})
    report = validate(observation)
    assert not report.standard.valid
    assert Flag.IMPOSSIBLE_EDGE in report.standard.flags


def test_mirrored_corner_cubie():
    # Swapping two stickers of one corner gives a mirror-image corner piece.
    facelets = swap(scrambled(6), CORNER_FACELETS[0][1:])
    report = validate(full(facelets))
    assert report.verdict == Verdict.INVALID
    assert Flag.IMPOSSIBLE_CORNER in report.flags
    assert Flag.IMPOSSIBLE_CORNER in validate(corner_view(facelets)).standard.flags


def test_twisted_corner_is_invalid_when_fully_visible():
    report = validate(full(twist_corner(scrambled(7), 0)))
    assert report.verdict == Verdict.INVALID
    assert Flag.ORIENTATION_INVARIANT_FAILURE in report.flags


def test_twisted_corner_is_valid_when_a_hidden_corner_can_compensate():
    observation = corner_view(twist_corner(scrambled(7), 0))
    report = validate(observation)
    assert report.verdict == Verdict.VALID_STANDARD
    assert_witness_agrees(observation, report)


def test_flipped_edge_is_invalid_when_fully_visible():
    report = validate(full(swap(scrambled(8), EDGE_FACELETS[5])))
    assert report.verdict == Verdict.INVALID
    assert Flag.ORIENTATION_INVARIANT_FAILURE in report.flags


def test_swapped_edges_violate_parity():
    facelets = scrambled(9)
    (a1, a2), (b1, b2) = EDGE_FACELETS[0], EDGE_FACELETS[1]
    report = validate(full(swap(facelets, (a1, b1), (a2, b2))))
    assert report.verdict == Verdict.INVALID
    assert report.flags == [Flag.NO_LEGAL_COMPLETION, Flag.PERMUTATION_PARITY_FAILURE]


def test_parity_failure_survives_one_hidden_edge():
    # With a single edge hidden its identity is forced, so parity is still decided.
    facelets = scrambled(10)
    swapped = swap(facelets, *zip(CORNER_FACELETS[0], CORNER_FACELETS[1]))
    c1, c2 = EDGE_FACELETS[7]
    observation = full(swapped).with_stickers({c1: None, c2: None})
    report = validate(observation)
    assert report.verdict == Verdict.INVALID
    assert Flag.PERMUTATION_PARITY_FAILURE in report.flags


def test_duplicated_edge_piece():
    facelets = scrambled(11)
    (uf_u, uf_f), (ur_u, ur_r) = EDGE_FACELETS[1], EDGE_FACELETS[0]
    observation = corner_view(facelets).with_stickers({ur_u: facelets[uf_u], ur_r: facelets[uf_f]})
    report = validate(observation)
    assert report.verdict == Verdict.INVALID
    assert Flag.DUPLICATE_PIECE in report.flags


def test_seven_colors():
    observation = corner_view(scrambled(12)).with_stickers({0: "P"})
    report = validate(observation)
    assert report.verdict == Verdict.INVALID
    assert Flag.TOO_MANY_COLORS in report.flags


def test_nothing_observed_is_inconclusive():
    report = validate(Observation((None,) * 54))
    assert report.verdict == Verdict.INCONCLUSIVE


def test_solved_cube_has_empty_scramble():
    report = validate(full(relabel(SOLVED, STANDARD_SCHEME.as_dict())))
    assert report.standard.witness.scramble == ""


def kociemba_accepts(facelets: str) -> bool:
    try:
        return not kociemba.solve(facelets).startswith("Error")
    except ValueError:
        return False


def test_full_states_agree_with_kociemba_validity():
    rng = random.Random(0)
    for _ in range(60):
        facelets = apply_moves(" ".join(rng.choice(FACES) + rng.choice(["", "'", "2"]) for _ in range(25)))
        s = list(facelets)
        for _ in range(rng.choice([0, 1, 2])):
            a, b = rng.sample([i for i in range(54) if i % 9 != 4], 2)
            s[a], s[b] = s[b], s[a]
        if rng.random() < 0.3:
            s = list(twist_corner("".join(s), rng.randrange(8)))
        mutated = "".join(s)
        report = validate(full(mutated), with_scramble=False)
        assert report.abstract.valid == kociemba_accepts(mutated), mutated
